use std::path::Path;

use crate::directory::Directory;
use Marker::{Extension, File};

/// A clue telling which kind of project a directory contains.
enum Marker {
    /// An exact file name, e.g. `Cargo.toml`.
    File(&'static str),
    /// Any file with this extension, e.g. `csproj` for `App.csproj`.
    Extension(&'static str),
}

impl Marker {
    fn is_found_in(&self, directory: &Directory) -> bool {
        match self {
            Marker::File(name) => directory.has_file(name),
            Marker::Extension(extension) => directory.has_file_with_extension(extension),
        }
    }
}

/// Recognizes one kind of project and the directories its tools generate.
pub struct Rule {
    name: &'static str,
    markers: &'static [Marker],
    artifacts: &'static [&'static str],
}

impl Rule {
    pub fn name(&self) -> &'static str {
        self.name
    }

    /// True when the directory contains at least one marker of this project type.
    pub fn matches(&self, directory: &Directory) -> bool {
        self.markers
            .iter()
            .any(|marker| marker.is_found_in(directory))
    }

    /// True when `path` is a directory generated by this project type.
    pub fn is_artifact(&self, path: &Path) -> bool {
        path.file_name()
            .is_some_and(|name| self.artifacts.iter().any(|artifact| name == *artifact))
    }
}

