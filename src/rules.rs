#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_a_star_dot_marker_as_an_extension() {
        assert!(matches!(
            Marker::from("*.csproj".to_string()),
            Marker::Extension(extension) if extension == "csproj"
        ));
        assert!(matches!(
            Marker::from("Cargo.toml".to_string()),
            Marker::File(name) if name == "Cargo.toml"
        ));
    }

    #[test]
    fn every_built_in_rule_is_valid() {
        for rule in built_in() {
            assert_eq!(rule.check(), Ok(()), "rule {}", rule.name());
        }
    }

    #[test]
    fn refuses_a_rule_without_markers_or_artifacts() {
        assert!(Rule::new("Empty", &[], &["out"]).check().is_err());
        assert!(Rule::new("Empty", &["x.json"], &[]).check().is_err());
        assert!(Rule::new(" ", &["x.json"], &["out"]).check().is_err());
    }

    #[test]
    fn refuses_artifacts_that_are_paths() {
        for artifact in ["..", ".", "", "out/debug"] {
            let rule = Rule::new("Bad", &["x.json"], &[artifact]);

            assert_eq!(
                rule.check(),
                Err("artifacts must be folder names, not paths"),
                "artifact {artifact:?}"
            );
        }
    }

    #[test]
    fn recognizes_an_artifact_by_its_folder_name() {
        let rule = Rule::new("Rust", &["Cargo.toml"], &["target"]);

        assert!(rule.is_artifact(Path::new("app/target")));
        assert!(!rule.is_artifact(Path::new("app/targets")));
    }
}
