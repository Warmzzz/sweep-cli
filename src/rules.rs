use std::ffi::OsStr;
use std::path::Path;

use serde::Deserialize;

use crate::directory::Directory;

/// A clue telling which kind of project a directory contains.
/// Written as text: `"Cargo.toml"` is an exact file name, `"*.csproj"` an extension.
#[derive(Debug, Deserialize)]
#[serde(from = "String")]
enum Marker {
    File(String),
    Extension(String),
}

impl From<String> for Marker {
    fn from(text: String) -> Self {
        match text.strip_prefix("*.") {
            Some(extension) => Marker::Extension(extension.to_string()),
            None => Marker::File(text),
        }
    }
}

impl Marker {
    fn is_found_in(&self, directory: &Directory) -> bool {
        match self {
            Marker::File(name) => directory.has_file(name),
            Marker::Extension(extension) => directory.has_file_with_extension(extension),
        }
    }
}

/// Recognizes one kind of project and the directories its tools generate.
/// Built-in rules and the user's own rules (from the config file) work the same way.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Rule {
    name: String,
    markers: Vec<Marker>,
    artifacts: Vec<String>,
}

impl Rule {
    pub fn new(name: &str, markers: &[&str], artifacts: &[&str]) -> Self {
        Self {
            name: name.to_string(),
            markers: markers
                .iter()
                .map(|marker| Marker::from(marker.to_string()))
                .collect(),
            artifacts: artifacts
                .iter()
                .map(|artifact| artifact.to_string())
                .collect(),
        }
    }

    pub fn name(&self) -> &str {
        &self.name
    }

    /// Returns `Ok` when the rule can be used, or what is wrong with it.
    pub fn check(&self) -> Result<(), &'static str> {
        if self.name.trim().is_empty() {
            return Err("the name is empty");
        }
        if self.markers.is_empty() {
            return Err("it needs at least one marker");
        }
        if self.artifacts.is_empty() {
            return Err("it needs at least one artifact");
        }
        // A plain folder name is its own file name: "a/b", ".." or "" are not.
        if self
            .artifacts
            .iter()
            .any(|artifact| Path::new(artifact).file_name() != Some(OsStr::new(artifact)))
        {
            return Err("artifacts must be folder names, not paths");
        }
        Ok(())
    }

    /// True when the directory contains at least one marker of this project type.
    pub fn matches(&self, directory: &Directory) -> bool {
        self.markers
            .iter()
            .any(|marker| marker.is_found_in(directory))
    }

    /// True when `path` is a directory generated by this project type.
    pub fn is_artifact(&self, path: &Path) -> bool {
        path.file_name().is_some_and(|name| {
            self.artifacts
                .iter()
                .any(|artifact| name == artifact.as_str())
        })
    }
}

